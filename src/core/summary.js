/**
 * CORE — SUMMARY & MINDMAP
 *
 * Pure generators that turn the digest analysis (chapters + key quotes) and
 * video metadata into shareable documents: a Markdown summary, a Mermaid
 * mindmap, and an XMind-compatible outline. No browser APIs are used.
 */

const SUMMARY_QUOTE_MAX_CHARS = 600;
const MINDMAP_LABEL_MAX_CHARS = 60;

function cleanLine(text) {
  return String(text || "")
    .trim()
    .replace(/\s+/g, " ");
}

/**
 * Markdown summary: metadata header + chapters + key quotes.
 */
function buildMarkdownSummary({ title, channelName, description, videoUrl, guide, chapters, keyQuotes }) {
  const lines = [];
  lines.push(`# ${cleanLine(title) || "Untitled Video"}`);
  lines.push("");
  if (channelName) lines.push(`- 频道 / Channel: ${cleanLine(channelName)}`);
  if (videoUrl) lines.push(`- URL: ${String(videoUrl).trim()}`);
  if (description) {
    lines.push("");
    lines.push("## 简介 / Description");
    lines.push("");
    lines.push(cleanLine(description));
  }

  lines.push("");
  if (guide) {
    const section = (heading, text, values, ordered = false) => {
      if (!text && !values?.length) return;
      lines.push(`## ${heading}`, "");
      if (text) lines.push(cleanLine(text), "");
      if (Array.isArray(values)) { values.forEach((value, index) => lines.push(`${ordered ? `${index + 1}.` : "-"} ${cleanLine(value)}`)); lines.push(""); }
    };
    section("本节目标", guide.goal);
    section("核心要点", "", guide.takeaways);
    section("可复用流程（根据字幕归纳）", "", guide.workflow, true);
    section("本例选择与适用条件", "", guide.exampleChoices);
    section("完成状态", guide.outcome);
    section("需要核实", "", guide.uncertainties);
  }
  lines.push("## 章节 / Chapters");
  lines.push("");
  const chapterList = Array.isArray(chapters) ? chapters : [];
  if (chapterList.length === 0) {
    lines.push("_No chapters available._");
  } else {
    chapterList.forEach((chapter, index) => {
      const stamp = chapter.timestamp || "";
      const title = cleanLine(chapter.title) || `Chapter ${index + 1}`;
      lines.push(`${index + 1}. **[${stamp}] ${title}**`);
      const summary = String(chapter.summary || "").trim();
      if (summary) summary.split(/\r?\n/).filter(line => line.trim()).forEach(line => lines.push(`   ${line.trim()}`));
    });
  }

  lines.push("");
  lines.push("## 关键引语 / Key Quotes");
  lines.push("");
  const quotes = Array.isArray(keyQuotes) ? keyQuotes : [];
  if (quotes.length === 0) {
    lines.push("_No key quotes available._");
  } else {
    quotes.forEach((quote) => {
      const stamp = quote.timestamp || "";
      const text = cleanLine(quote.quote).slice(0, SUMMARY_QUOTE_MAX_CHARS);
      lines.push(`- **[${stamp}]** ${text}`);
    });
  }

  lines.push("");
  lines.push("---");
  lines.push("Generated by VideoNotes");
  return lines.join("\n");
}

/**
 * Mermaid mindmap source: root = video title, one node per chapter, with the
 * chapter summary as a child node.
 */
function buildMindmapMarkdown({ title, chapters }) {
  const rootLabel = cleanLine(title).slice(0, MINDMAP_LABEL_MAX_CHARS) || "Video";
  const lines = [];
  lines.push("mindmap");
  lines.push(`  root((${rootLabel}))`);
  (Array.isArray(chapters) ? chapters : []).forEach((chapter) => {
    const stamp = chapter.timestamp || "";
    const chapterLabel =
      `${stamp ? `${stamp} ` : ""}${cleanLine(chapter.title)}`.slice(
        0,
        MINDMAP_LABEL_MAX_CHARS,
      );
    if (!chapterLabel) return;
    lines.push(`    ${chapterLabel}`);
    const summary = cleanLine(chapter.summary).slice(0, MINDMAP_LABEL_MAX_CHARS);
    if (summary) lines.push(`      ${summary}`);
  });
  return lines.join("\n");
}

/**
 * XMind / outline-compatible Markdown: an indented heading hierarchy built
 * from the chapters.
 */
function buildOutlineMarkdown({ title, chapters }) {
  const lines = [];
  lines.push(`# ${cleanLine(title) || "Untitled Video"}`);
  (Array.isArray(chapters) ? chapters : []).forEach((chapter) => {
    const stamp = chapter.timestamp || "";
    const chapterTitle = cleanLine(chapter.title) || "Chapter";
    lines.push(`## ${stamp ? `${stamp} ` : ""}${chapterTitle}`);
    const summary = cleanLine(chapter.summary);
    if (summary) lines.push(`### ${summary}`);
  });
  return lines.join("\n");
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    buildMarkdownSummary,
    buildMindmapMarkdown,
    buildOutlineMarkdown,
  };
}
