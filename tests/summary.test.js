const test = require("node:test");
const assert = require("node:assert/strict");

const {
  buildMarkdownSummary,
  buildMindmapMarkdown,
  buildOutlineMarkdown,
} = require("../src/core/summary.js");

const SAMPLE = {
  title: "A Great Talk",
  channelName: "Example Channel",
  description: "A short description.",
  videoUrl: "https://youtube.com/watch?v=abc123",
  chapters: [
    {
      timestamp: "0:00",
      timestampSeconds: 0,
      title: "Introduction",
      summary: "Greets the audience and sets the agenda.",
    },
    {
      timestamp: "5:30",
      timestampSeconds: 330,
      title: "Core Ideas",
      summary: "Explains the main concepts in detail.",
    },
  ],
  keyQuotes: [
    { timestamp: "1:15", quote: "Learning is a journey." },
    { timestamp: "8:00", quote: "Practice beats theory." },
  ],
};

test("buildMarkdownSummary includes metadata, chapters, and quotes", () => {
  const md = buildMarkdownSummary(SAMPLE);
  assert.match(md, /^# A Great Talk$/m);
  assert.match(md, /频道 \/ Channel: Example Channel/);
  assert.match(md, /URL: https:\/\/youtube\.com\/watch\?v=abc123/);
  assert.match(md, /## 章节 \/ Chapters/);
  assert.match(md, /1\. \*\*\[0:00\] Introduction\*\*/);
  assert.match(md, /Greets the audience and sets the agenda/);
  assert.match(md, /## 关键引语 \/ Key Quotes/);
  assert.match(md, /Learning is a journey/);
  assert.match(md, /Generated by YouTube Digest/);
});

test("buildMarkdownSummary tolerates missing analysis data", () => {
  const md = buildMarkdownSummary({});
  assert.match(md, /^# Untitled Video$/m);
  assert.match(md, /_No chapters available\._/);
  assert.match(md, /_No key quotes available\._/);
});

test("buildMindmapMarkdown emits a Mermaid mindmap rooted at the title", () => {
  const mm = buildMindmapMarkdown(SAMPLE);
  assert.match(mm, /^mindmap$/m);
  assert.match(mm, /root\(\(A Great Talk\)\)/);
  assert.match(mm, /0:00 Introduction/);
  assert.match(mm, /Explains the main concepts in detail/);
});

test("buildOutlineMarkdown emits an XMind-compatible heading hierarchy", () => {
  const outline = buildOutlineMarkdown(SAMPLE);
  assert.match(outline, /^# A Great Talk$/m);
  assert.match(outline, /^## 0:00 Introduction$/m);
  assert.match(outline, /^### Greets the audience and sets the agenda\.$/m);
});
